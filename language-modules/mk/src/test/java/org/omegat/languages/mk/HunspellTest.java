package org.omegat.languages.mk;

import org.junit.Test;

import org.omegat.core.spellchecker.ISpellChecker;
import org.omegat.languages.LanguageModuleTestBase;
import org.omegat.spellchecker.lucene.LuceneHunSpellChecker;

/**
 * Loads the bundled Macedonian dictionary through the module and checks one
 * word from the word list against one that is not.
 *
 * Generated by language-modules/dictionaries/tools/generate_modules.py.
 *
 * @author stephan.pakebusch at zollsoft.de
 */
public class HunspellTest extends LanguageModuleTestBase {

    private static final String LANGUAGE = "mk";
    private static final String GOOD = "\u043c\u0435\u043a\u0441\u0438\u043a\u0430\u043d\u043a\u0438";
    private static final String BAD = "\u0438\u043a\u043d\u0430\u043a\u0438\u0441\u043a\u0435\u043c";

    @Test
    public void testDictionary() throws Exception {
        MacedonianPlugin.loadPlugins();
        ISpellChecker checker = new LuceneHunSpellChecker(60_000);
        testDictionaryHelper(checker, LANGUAGE, GOOD, BAD);
    }
}
