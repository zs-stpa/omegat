"""Generate the dictionary artifacts and language modules from sources.json.

For every language marked ``bundle`` the script writes

- ``dictionary-hunspell-<xx>/artifact.json`` for the included artifact build,
- ``language-modules/<xx>/`` with build.gradle, gradle.properties, the
  one-line plugin class and a spell check test,
- the ``include`` lines in settings.gradle and the ``dictionary-hunspell-<xx>`` aliases
  in gradle/libs.versions.toml.

Existing generated files are overwritten; hand-written modules (those with
a LanguageTool dependency) are never touched. Run from this directory with
``python3 -I tools/generate_modules.py [--normalized DIR]``; the normalised
pairs are only needed to pick a sample word for each module's test.

@author stephan.pakebusch at zollsoft.de
"""
