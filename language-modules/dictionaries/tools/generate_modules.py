def class_name(name):
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    return re.sub(r"[^A-Za-z]", "", ascii_name) + "Plugin"


def stem_for(source):
    """File stem of a pair: the first locale spelled xx_YY, or the wooorm code."""
    if source["collection"] == "wooorm":
        return source["locales"][0].replace("-", "_")
    parts = source["locales"][0].split("-")
    stem = parts[0].lower()
    for p in parts[1:]:
        stem += "_" + (p.title() if len(p) == 4 else p.upper())
    return stem


def java_string(text):
    return "".join(ch if 0x20 <= ord(ch) < 0x7f and ch not in '"\\' else f"\\u{ord(ch):04x}" for ch in text)


def normalized_stem(source, normalized_root):
    """Where the scanner wrote the normalised pair: the manifest keeps the path
    relative to the normalisation directory, --normalized names that directory."""
    norm = (source.get("import") or {}).get("normalized")
    if not norm or not normalized_root:
        return None
    return str(Path(normalized_root) / norm)


def sample_words(normalized_stem, count=6):
    """Plain words spread over the word list, longest first, or []."""
    dic = Path(normalized_stem + ".dic") if normalized_stem else None
    if dic is None or not dic.is_file():
        return []
    words = []
    with open(dic, encoding="utf-8") as fh:
        next(fh, None)
        for line in fh:
            word = line.split("/")[0].split("\t")[0].strip()
            if 3 <= len(word) <= 12 and word == word.lower() \
                    and all(unicodedata.category(ch)[0] in "LM" for ch in word):
                words.append(word)
    if not words:
        return []
    step = max(1, len(words) // (count + 1))
    picks = [words[i * step] for i in range(1, count + 1) if i * step < len(words)]
    # Deterministic order: longest first, ties alphabetically.
    return sorted(set(picks), key=lambda w: (-len(w), w))


def verified_words(normalized_stem, lucene_classpath):
    """(good, bad) pair the Lucene speller agrees with, or (None, None).

    Candidates come from the word list; the bad word is the good one
    reversed, which stays in the language's script (Latin letters would be
    waved through for some scripts) but is no word.
    """
    candidates = sample_words(normalized_stem)
    if not candidates:
        return None, None
    if not lucene_classpath:
        return candidates[0], candidates[0][::-1]
    words = []
    for w in candidates:
        words += [w, w[::-1]]
    proc = subprocess.run(["java", "-cp", lucene_classpath, "org.omegat.dictionaries.LuceneHunspellCheck",
                           normalized_stem] + words, capture_output=True, text=True, timeout=600)
    verdict = dict(part.rsplit("=", 1) for part in proc.stdout.split(" ")[3:] if "=" in part)
    for w in candidates:
        if verdict.get(w) == "ok" and verdict.get(w[::-1]) == "bad":
            return w, w[::-1]
    return None, None


def version_for(snapshot):
    date = datetime.date.fromisoformat(snapshot["date"][:10])
    return date.strftime("%Y.%m.%d")


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")
        return True
    return False


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--manifest", default=str(HERE / "sources.json"))
    ap.add_argument("--normalized", help="directory with the normalised pairs; needed only to choose test words anew")
    ap.add_argument("--lucene-classpath", default=None,
                    help="class path with Lucene and org.omegat.dictionaries.LuceneHunspellCheck to verify test words")
    ap.add_argument("--refresh-test-words", action="store_true",
                    help="pick the test words anew instead of reusing those kept in artifact.json")
    ap.add_argument("--dry-run", action="store_true",
                    help="write nothing; list checked-in files that differ from the generator output, exit 1 on drift")
    args = ap.parse_args()
    manifest = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
    # Header year from the newest snapshot: regenerating later must not rewrite every file.
    year = max(datetime.date.fromisoformat(s["date"][:10]).year for s in manifest["snapshots"].values())
    generated = []
    aliases = {}
    drift = 0
    for lang in manifest["languages"]:
        if not lang.get("bundle"):
            continue
        xx = lang["language"]
        name = NAMES.get(xx)
        if name is None:
            raise SystemExit(f"no English name for {xx}; add it to NAMES")
        selected = [s for s in lang["sources"] if s.get("selected")]
        if not selected:
            raise SystemExit(f"{xx}: no selected source")
        snapshot = manifest["snapshots"][selected[0]["collection"]]
        version = version_for(snapshot)
        license_expr = (selected[0]["license_spdx"] or "").strip("()").replace(" OR ", " / ")
        pairs = []
        registrations = []
        good, bad, test_stem = None, None, None
        prior_artifact = HERE / f"dictionary-hunspell-{xx}" / "artifact.json"
        if prior_artifact.exists() and not args.refresh_test_words:
            # Keeps regeneration reproducible without the Lucene checker.
            prior = json.loads(prior_artifact.read_text(encoding="utf-8")).get("test") or {}
            if prior:
                good, bad, test_stem = prior["good"], prior["bad"], prior["stem"]
        for s in selected:
            stem = stem_for(s)
            codes = sorted({loc.replace("-", "_") for loc in s["locales"]} - {stem})
            pairs.append({
                "stem": stem, "codes": codes, "words": s["words"],
                "affUrl": s["url_aff"], "affSha256": s["sha256_aff"],
                "dicUrl": s["url_dic"], "dicSha256": s["sha256_dic"],
                "upstream": s["upstream_urls"][0] if s["upstream_urls"] else s["url_aff"].rsplit("/", 3)[0],
                "documents": [{"name": d["name"], "url": d["url"], "sha256": d["sha256"]} for d in s["documents"]],
            })
            quoted = ", ".join(f'"{c}"' for c in [stem] + codes)
            registrations.append(f"        BundledHunspellDictionary.register({quoted});")
            if good is None:
                good, bad = verified_words(normalized_stem(s, args.normalized), args.lucene_classpath)
                if good is not None:
                    # The test must ask for the pair the word came from (tlh is
                    # pIqaD in private-use characters, tlh_Latn is Latin).
                    test_stem = stem
        artifact = {
            "language": xx, "languageName": name, "license": license_expr, "version": version,
            # Pinned commit and the branch to compare against (checkUpstream task).
            "commit": snapshot["commit"], "branch": snapshot.get("branch") or "HEAD",
            "pairs": pairs,
            # Words the module test uses, verified with Lucene when first chosen.
            "test": {"stem": test_stem or pairs[0]["stem"], "good": good, "bad": bad},
        }
        files = {
            HERE / f"dictionary-hunspell-{xx}" / "artifact.json": json.dumps(artifact, indent=2, ensure_ascii=False) + "\n",
        }
        cls = class_name(name)
        alias = xx
        module = ROOT / "language-modules" / xx
        files[module / "build.gradle"] = BUILD_GRADLE.format(xx=xx, alias=alias)
        files[module / "gradle.properties"] = GRADLE_PROPERTIES.format(
            license=license_expr, name=name, xx=xx, cls=cls, upstream=pairs[0]["upstream"])
        pkg = module / "src" / "main" / "java" / "org" / "omegat" / "languages" / xx
        files[pkg / f"{cls}.java"] = PLUGIN_JAVA.format(year=year, xx=xx, name=name, cls=cls,
                                                        registrations="\n".join(registrations))
        test_pkg = module / "src" / "test" / "java" / "org" / "omegat" / "languages" / xx
        test_code = test_stem or pairs[0]["stem"]
        files[test_pkg / "HunspellTest.java"] = TEST_JAVA.format(
            year=year, xx=xx, name=name, cls=cls, code=test_code,
            good=java_string(good), bad=java_string(bad))
        if good is None:
            raise SystemExit(f"{xx}: no sample words found under --normalized; refusing to write a placeholder test")
        for path, text in files.items():
            if args.dry_run:
                if not path.exists() or path.read_text(encoding="utf-8") != text:
                    print("would write", path.relative_to(ROOT))
                    drift += 1
            elif write(path, text):
                generated.append(path)
        aliases[xx] = version
    drift += update_settings(aliases, args.dry_run)
    drift += update_catalog(aliases, args.dry_run)
    print(f"{len(aliases)} languages, {len(generated)} files written")
    if args.dry_run:
        # Non-zero when the checked-in files drifted from the generator.
        print(f"{drift} files differ from the generator output")
        raise SystemExit(1 if drift else 0)


def update_settings(aliases, dry_run):
    settings = ROOT / "settings.gradle"
    text = settings.read_text(encoding="utf-8")
    existing = set(re.findall(r'"language-modules:([a-z]+)"', text))
    lines = text.split("\n")
    for xx in sorted(set(aliases) - existing):
        new_line = f'        "language-modules:{xx}",'
        idx = [i for i, l in enumerate(lines) if re.match(r'\s*"language-modules:[a-z]+",', l)]
        pos = next((i for i in idx if lines[i].strip() > new_line.strip()), idx[-1] + 1)
        lines.insert(pos, new_line)
    text = "\n".join(lines)
    if 'includeBuild("language-modules/dictionaries")' not in text:
        # Outside pluginManagement: builds included there only substitute plugins.
        text = text.replace("rootProject.name = 'OmegaT'\n",
                            "rootProject.name = 'OmegaT'\n"
                            "// Hunspell dictionary artifacts (org.omegat.dictionaries:dictionary-hunspell-<xx>) for the\n"
                            "// dictionary-only language modules, built from the pinned upstream files until\n"
                            "// they are published.\n"
                            'includeBuild("language-modules/dictionaries")\n', 1)
    return commit(settings, text, dry_run)


CATALOG_COMMENT = ("# Hunspell dictionary artifacts (language-modules/dictionaries); the name must not start\n"
                   "# with another provided artifact's name (hunspell-*), the providedModuleLib glob would take them\n")


def update_catalog(aliases, dry_run):
    catalog = ROOT / "gradle" / "libs.versions.toml"
    text = catalog.read_text(encoding="utf-8")
    text = re.sub(r"^dictionary-hunspell-[a-z]+ = \{group = \"org\.omegat\.dictionaries\".*\n", "", text, flags=re.M)
    text = text.replace(CATALOG_COMMENT, "")
    block = "".join(f'dictionary-hunspell-{xx} = {{group = "org.omegat.dictionaries", name = "dictionary-hunspell-{xx}", version = "{v}"}}\n'
                    for xx, v in sorted(aliases.items()))
    marker = re.search(r"^languagetool-zh = .*\n", text, flags=re.M)
    text = text[:marker.end()] + CATALOG_COMMENT + block + text[marker.end():]
    return commit(catalog, text, dry_run)


def commit(path, text, dry_run):
    """Writes the file unless --dry-run; returns 1 when it differs from the generator output."""
    if path.read_text(encoding="utf-8") == text:
        return 0
    if dry_run:
        print("would update", path.relative_to(ROOT))
    else:
        path.write_text(text, encoding="utf-8")
    return 1


if __name__ == "__main__":
    main()
